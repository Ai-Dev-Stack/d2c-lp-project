"""
架空D2Cブランド「着色料無添加サプリ定期便」の顧客マスターデータ生成スクリプト

目的:
  「購入に至る顧客を知り、その顧客に合うLPを作成する」の分析ステップで使う
  顧客属性・購入行動(LTV算出用)・アンケート回答(悩み分析用)を、
  意図的な相関を仕込んだ状態で生成する。

意図した相関(分析で「発見」できるように仕込んだもの):
  - 30代・40代前半 x SNS広告経由 の顧客は継続月数が長く、LTVが高い
  - 紹介(友人・家族)経由の顧客は継続月数が最も長い
  - 検索広告経由の顧客は継続月数が短く、早期離脱しやすい
  - 年代によって悩みカテゴリの傾向が異なる(30代=疲労感、50代=更年期 など)
  - 優良顧客層(LTV上位)は「疲労感」「続けやすさ」関連の回答が多い
"""

import numpy as np
import pandas as pd
from datetime import datetime, timedelta

rng = np.random.default_rng(42)
N = 600

# ---------------------------------------------------------
# 1. 年代・性別・居住地域
# ---------------------------------------------------------
age_groups = ["20代", "30代", "40代", "50代", "60代以上"]
age_weights = [0.14, 0.32, 0.26, 0.18, 0.10]
age = rng.choice(age_groups, size=N, p=age_weights)

# 女性向けD2Cブランドという想定で性別を偏らせる
gender = rng.choice(["女性", "男性"], size=N, p=[0.86, 0.14])

region = rng.choice(["都市部", "地方"], size=N, p=[0.58, 0.42])

# ---------------------------------------------------------
# 2. 流入チャネル(年代によって傾向を変える)
# ---------------------------------------------------------
channels = ["SNS広告", "検索広告", "自然検索", "友人・家族の紹介"]
channel_probs_by_age = {
    "20代": [0.55, 0.15, 0.20, 0.10],
    "30代": [0.45, 0.15, 0.20, 0.20],
    "40代": [0.30, 0.20, 0.30, 0.20],
    "50代": [0.15, 0.20, 0.45, 0.20],
    "60代以上": [0.08, 0.12, 0.55, 0.25],
}
channel = np.array([
    rng.choice(channels, p=channel_probs_by_age[a]) for a in age
])

# ---------------------------------------------------------
# 3. 継続月数(=LTV算出のもと)。チャネル・年代で意図的に差をつける
# ---------------------------------------------------------
# ベースとなる平均継続月数(ガンマ分布の平均に相当)
base_by_channel = {
    "SNS広告": 7.0,
    "検索広告": 3.5,
    "自然検索": 5.5,
    "友人・家族の紹介": 9.0,
}
age_bonus = {"20代": -1.0, "30代": 2.0, "40代": 1.0, "50代": -0.5, "60代以上": -1.5}

continuation_months = []
for a, c in zip(age, channel):
    mean_months = max(base_by_channel[c] + age_bonus[a], 1.0)
    # ガンマ分布で右に裾を引く継続期間を生成(観測上限24ヶ月でキャップ)
    val = rng.gamma(shape=2.0, scale=mean_months / 2.0)
    continuation_months.append(min(round(val, 1), 24.0))
continuation_months = np.array(continuation_months)

# 継続中か解約済みかのステータス(継続月数が長いほど「継続中」になりやすい)
status_prob_active = np.clip(continuation_months / 24.0 + 0.15, 0.05, 0.9)
status = np.array([
    "継続中" if rng.random() < p else "解約済み" for p in status_prob_active
])

# ---------------------------------------------------------
# 4. 月額単価・LTV
# ---------------------------------------------------------
monthly_price = rng.choice([4980, 6980], size=N, p=[0.8, 0.2])
ltv = np.round(continuation_months * monthly_price).astype(int)

# ---------------------------------------------------------
# 5. 初回購入日(過去24ヶ月以内でランダム)
# ---------------------------------------------------------
today = datetime(2026, 9, 1)
first_purchase_date = [
    (today - timedelta(days=int(rng.uniform(30, 730)))).strftime("%Y-%m-%d")
    for _ in range(N)
]

# ---------------------------------------------------------
# 6. 購入きっかけ(流入チャネルと相関させつつ、多少のブレを持たせる)
# ---------------------------------------------------------
kikkake_map = {
    "SNS広告": ["SNSで見て", "広告を見て"],
    "検索広告": ["広告を見て", "検索して自分で見つけた"],
    "自然検索": ["検索して自分で見つけた", "口コミサイトで見て"],
    "友人・家族の紹介": ["友人・家族の紹介", "SNSで見て"],
}
kikkake = np.array([
    rng.choice(kikkake_map[c], p=[0.75, 0.25]) for c in channel
])

# ---------------------------------------------------------
# 7. 悩みカテゴリ(年代によって傾向を変える)
# ---------------------------------------------------------
worries = ["慢性的な疲労感", "成分・添加物への不安", "肌の調子", "更年期特有の不調", "家族の健康管理"]
worry_probs_by_age = {
    "20代": [0.20, 0.25, 0.35, 0.05, 0.15],
    "30代": [0.42, 0.28, 0.10, 0.05, 0.15],
    "40代": [0.35, 0.25, 0.08, 0.17, 0.15],
    "50代": [0.25, 0.15, 0.05, 0.40, 0.15],
    "60代以上": [0.15, 0.10, 0.05, 0.30, 0.40],
}
worry = np.array([
    rng.choice(worries, p=worry_probs_by_age[a]) for a in age
])

# ---------------------------------------------------------
# 8. 自由記述(悩みカテゴリに応じたテンプレ+軽いバリエーション)
# ---------------------------------------------------------
free_text_templates = {
    "慢性的な疲労感": [
        "仕事と育児の両立で、朝起きても疲れが取れていない感じがずっと続いています。",
        "忙しい毎日で、寝ても疲れが抜けにくくなってきました。続けやすいものを探していました。",
        "年齢のせいか、以前より疲れやすくなった気がしていて悩んでいました。",
    ],
    "成分・添加物への不安": [
        "市販のサプリは成分表示が分かりにくく、添加物が気になって続けられませんでした。",
        "着色料や保存料が入っていないか、購入前に必ず確認するようにしています。",
        "子どもも口にする可能性があるので、無添加であることを重視しています。",
    ],
    "肌の調子": [
        "肌の調子が不安定で、体の内側からケアできるものを探していました。",
        "季節の変わり目に肌荒れしやすく、食事だけでは補いきれないと感じていました。",
    ],
    "更年期特有の不調": [
        "更年期特有のほてりや気分の浮き沈みがあり、体調管理に不安を感じていました。",
        "この年代特有の体の変化に、食事だけで対応するのが難しいと感じていました。",
    ],
    "家族の健康管理": [
        "家族全員の健康を考えて、安心して続けられるものを探していました。",
        "毎日の食事で不足しがちな栄養を、家族分まとめて補いたいと思っていました。",
    ],
}
free_text = np.array([
    rng.choice(free_text_templates[w]) for w in worry
])

# ---------------------------------------------------------
# データフレーム化
# ---------------------------------------------------------
df = pd.DataFrame({
    "顧客ID": [f"C{str(i).zfill(4)}" for i in range(1, N + 1)],
    "性別": gender,
    "年代": age,
    "居住地域": region,
    "流入チャネル": channel,
    "初回購入日": first_purchase_date,
    "継続月数": continuation_months,
    "ステータス": status,
    "月額単価": monthly_price,
    "累計購入金額(LTV)": ltv,
    "購入きっかけ": kikkake,
    "悩みカテゴリ": worry,
    "悩みの自由記述": free_text,
})

# 出力
csv_path = "/mnt/user-data/outputs/customer_data.csv"
xlsx_path = "/mnt/user-data/outputs/customer_data.xlsx"
df.to_csv(csv_path, index=False, encoding="utf-8-sig")
df.to_excel(xlsx_path, index=False, sheet_name="顧客マスターデータ")

print(df.head(10).to_string())
print("\n件数:", len(df))
print("\n--- 年代別 平均LTV(検算用) ---")
print(df.groupby("年代")["累計購入金額(LTV)"].mean().round(0))
print("\n--- 流入チャネル別 平均継続月数(検算用) ---")
print(df.groupby("流入チャネル")["継続月数"].mean().round(1))
print("\n--- 年代別 悩みカテゴリの分布(検算用) ---")
print(pd.crosstab(df["年代"], df["悩みカテゴリ"]))
